-- Run this in Supabase Dashboard -> SQL Editor -> New query.
-- Intended for a NEW/empty Supabase project. It creates the four app tables.

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'customer'
    CHECK (role IN ('customer', 'employee'))
);

CREATE TABLE IF NOT EXISTS categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS complaints (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id VARCHAR(20) NOT NULL UNIQUE,
  user_id INTEGER NOT NULL REFERENCES users(id),
  category VARCHAR(50) NOT NULL REFERENCES categories(category_name),
  subject VARCHAR(150) NOT NULL,
  description TEXT NOT NULL,
  transaction_id VARCHAR(50),
  transaction_amount NUMERIC(12,2),
  transaction_date DATE,
  status VARCHAR(20) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'In Progress', 'Resolved', 'Closed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS complaint_updates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id VARCHAR(20) NOT NULL REFERENCES complaints(complaint_id),
  status VARCHAR(20) NOT NULL
    CHECK (status IN ('Pending', 'In Progress', 'Resolved', 'Closed')),
  remark TEXT,
  updated_by INTEGER NOT NULL REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

